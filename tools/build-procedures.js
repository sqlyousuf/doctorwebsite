#!/usr/bin/env node
/*
 * Generates the procedures/ pages from tools/content/procedures.js.
 *
 *     node tools/build-procedures.js
 *
 * Shares its chrome with the Patient Center pages via tools/chrome.js, so the
 * header, footer and sprite stay in lockstep with index.html.
 *
 * A page with `draft: true` gets a review banner, a noindex robots tag, and is
 * excluded from the sitemap — so a page awaiting the surgeon's sign-off can be
 * previewed on the live site without being indexed or offered to patients.
 */

const fs = require('fs');
const path = require('path');
const { pages, PHONE, PHONE_HREF } = require('./content/procedures.js');
const { ORIGIN } = require('./site.js');
const { root, sprite, footerFor, apptModalFor, buildNav, header, tail, escapeAttr, plain } = require('./chrome.js');

const outDir = path.join(root, 'procedures');
const footer = footerFor({ up: '../', pcPrefix: '../patient-center/', home: '../index.html' });
const nav = buildNav({ lang: 'en', up: '../', home: '../index.html', pcPrefix: '../patient-center/' });

const breadcrumb = (title, slug) => ({
  '@context': 'https://schema.org',
  '@type': 'BreadcrumbList',
  itemListElement: [
    { '@type': 'ListItem', position: 1, name: 'Home', item: `${ORIGIN}/` },
    { '@type': 'ListItem', position: 2, name: 'Procedures', item: `${ORIGIN}/#services` },
    { '@type': 'ListItem', position: 3, name: title, item: `${ORIGIN}/procedures/${slug}.html` },
  ],
});

/** Pull the FAQ pairs straight out of the rendered body, so the two cannot disagree. */
function faqSchema(body) {
  const items = [...body.matchAll(/<summary>(.*?)<span class="faq-icon"[\s\S]*?<\/summary>([\s\S]*?)<\/details>/g)].map(
    ([, q, a]) => ({
      '@type': 'Question',
      name: plain(q).trim(),
      acceptedAnswer: { '@type': 'Answer', text: plain(a).replace(/\s+/g, ' ').trim() },
    })
  );
  return items.length ? { '@context': 'https://schema.org', '@type': 'FAQPage', mainEntity: items } : null;
}

const draftBanner = (page) => `<aside class="draft-banner">
  <div class="container">
    <p class="draft-title"><svg aria-hidden="true"><use href="#ic-info"/></svg> Draft — not yet reviewed by Dr. Wadiwala</p>
    <p>This page is a working draft. Every clinical statement on it was carried across from pages the practice already
    publishes; nothing was written from scratch. It is served <code>noindex</code> and kept out of the sitemap until it
    is signed off.</p>
    <p class="draft-sub">Before publishing, please confirm:</p>
    <ol class="prose-steps">
${page.reviewNotes.map((n) => `      <li>${n}</li>`).join('\n')}
    </ol>
  </div>
</aside>`;

function renderPage(page) {
  const title = plain(page.title);
  const url = `${ORIGIN}/procedures/${page.slug}.html`;
  const faq = faqSchema(page.body);
  const procedure = {
    '@context': 'https://schema.org',
    ...page.procedureSchema,
    url,
    provider: { '@id': `${ORIGIN}/#clinic` },
  };

  const blocks = [breadcrumb(title, page.slug), procedure, faq]
    .filter(Boolean)
    .map((b) => `<script type="application/ld+json">\n${JSON.stringify(b, null, 2)}\n</script>`)
    .join('\n');

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${page.seoTitle || `${title} | Houston Surgical Weight Loss`}</title>
<meta name="description" content="${escapeAttr(page.description)}">
${page.draft ? '<meta name="robots" content="noindex, nofollow">\n' : ''}<link rel="canonical" href="${url}">
<link rel="icon" type="image/png" href="../media/favicon.png">
<link rel="apple-touch-icon" href="../media/favicon.png">
<meta property="og:type" content="article">
<meta property="og:site_name" content="Houston Surgical Weight Loss">
<meta property="og:url" content="${url}">
<meta property="og:title" content="${escapeAttr(title)}">
<meta property="og:description" content="${escapeAttr(page.description)}">
<meta property="og:image" content="${ORIGIN}/media/img/${path.basename(page.image)}">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${escapeAttr(title)}">
<meta name="twitter:description" content="${escapeAttr(page.description)}">
<meta name="twitter:image" content="${ORIGIN}/media/img/${path.basename(page.image)}">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Josefin+Sans:wght@200;300;400;600&family=Lato:wght@300;400;700&display=swap" rel="stylesheet">
<link rel="stylesheet" href="../css/style.css">
${blocks}
<!-- Generated by tools/build-procedures.js — do not edit by hand. -->
</head>
<body>

${sprite}

<!-- ======================= HEADER ======================= -->
${header({ nav, lang: 'en', up: '../', home: '../index.html' })}
${page.draft ? '\n' + draftBanner(page) + '\n' : ''}
<!-- ======================= PAGE HERO ======================= -->
<section class="page-hero" id="top">
  <img class="page-hero-img" src="${page.image}" alt="" loading="eager" fetchpriority="high">
  <div class="page-hero-scrim" aria-hidden="true"></div>
  <div class="page-hero-inner container">
    <p class="page-hero-kicker">Procedures</p>
    <h1 class="page-hero-title">${page.title}</h1>
    <p class="page-hero-tag">${page.tagline}</p>
  </div>
</section>

<nav class="crumbs" aria-label="Breadcrumb">
  <div class="container">
    <a href="../index.html">Home</a>
    <span aria-hidden="true">/</span>
    <a href="../index.html#services">Procedures</a>
    <span aria-hidden="true">/</span>
    <span aria-current="page">${title}</span>
  </div>
</nav>

<section class="proc-stats">
  <div class="container">
    <dl class="proc-stat-row">
${page.stats.map(([f, l]) => `      <div><dt>${f}</dt><dd>${l}</dd></div>`).join('\n')}
    </dl>
  </div>
</section>

<!-- ======================= CONTENT ======================= -->
<article class="pad-lg">
  <div class="container narrow prose">
${page.body.trim()}
  </div>
</article>

<!-- ======================= CTA ======================= -->
<section class="pc-cta">
  <div class="container center-block">
    <h2 class="display center">Find Out If You Qualify</h2>
    <p class="intro center">Your first consultation is free, in person or virtual. We will check your insurance and
    talk you through your options — no obligation.</p>
    <div class="contact-actions">
      <a href="${PHONE_HREF}" class="btn btn-solid"><svg><use href="#ic-phone"/></svg> ${PHONE}</a>
      <a href="../index.html#contact" class="btn btn-outline-light" data-appt-open>Request a Consultation</a>
    </div>
  </div>
</section>

${footer}

${apptModalFor('en')}

${tail({ lang: 'en', twin: '../es/index.html', home: '../index.html' })}

<script src="../js/main.js"></script>
</body>
</html>
`;
}

fs.mkdirSync(outDir, { recursive: true });
for (const page of pages) {
  fs.writeFileSync(path.join(outDir, `${page.slug}.html`), renderPage(page), 'utf8');
}

const drafts = pages.filter((p) => p.draft).length;
console.log(
  `build-procedures: wrote ${pages.length} page(s) to procedures/` +
    (drafts ? ` — ${drafts} draft, noindex and excluded from the sitemap` : '')
);
